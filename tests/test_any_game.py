# --------------------------------------------------------------------------- music-enhance

def tone(path: Path, seconds: float = 4, volume: float = 1.0) -> Path:
    """A stereo 1 kHz sine; lavfi's sine has a peak of 1/8, so volume 1 reads about -18 LUFS."""
    return lavfi(path, "-f", "lavfi", "-i", f"sine=frequency=1000:duration={seconds}:sample_rate=48000", "-af",
                 f"volume={volume},pan=stereo|c0=c0|c1=c0", "-c:a", "pcm_s16le")


@FFMPEG
@pytest.mark.parametrize("preset, target", [("music", -14.0), ("trailer", -14.0), ("voice", -16.0), ("game-sfx", -18.0)])
def test_enhance_a_tone_lands_on_the_preset(tmp_path, capsys, preset, target):
    src = tone(tmp_path / "tone.wav", volume=0.2)                                      # about -32 LUFS
    wise("music-enhance", src, "--for", preset, "--json")
    r = json.loads(capsys.readouterr().out)
    f = r["files"][0]
    out = tmp_path / "tone.enhanced.wav"
    assert r["ok"] and r["preset"] == preset and r["target"] == {"lufs": target, "true_peak_dbtp": -1.0} and Path(f["out"]) == out
    assert abs(f["before"]["integrated_lufs"] - -32.0) < 0.5
    after = music_enhance.measure(str(out))                                            # an independent reading of the file
    assert abs(after["integrated_lufs"] - target) <= 0.5 and after["true_peak_dbfs"] <= -1.0
    assert f["method"] == "gain" and abs(f["gain_db"] - (target + 32.0)) < 0.5         # peaks fit: one clean gain change
    assert (after["sample_rate"], after["channels"], after["codec"]) == (48000, 2, "pcm_s16le")
    assert src.stat().st_size > 0 and abs(music_enhance.measure(str(src))["integrated_lufs"] - -32.0) < 0.5   # the input is untouched


@FFMPEG
def test_enhance_uses_the_limiter_when_a_gain_would_clip(tmp_path, capsys):
    # pink noise that swells and fades: its peaks sit far above its average, so +22 dB of plain gain would clip
    src = lavfi(tmp_path / "dyn.wav", "-f", "lavfi", "-i", "anoisesrc=d=8:c=pink:r=44100:a=0.25:seed=7", "-af", "tremolo=f=0.5:d=0.9,volume=0.5", "-ac", "2")
    out = tmp_path / "out" / "dyn.flac"
    wise("music-enhance", src, "-o", out, "--report", tmp_path / "report.json")
    text = capsys.readouterr().out
    assert "loudnorm's second pass" in text and "result:        on target" in text and "before" in text and "after" in text
    rep = json.loads((tmp_path / "report.json").read_text())["files"][0]
    assert rep["method"] == "loudnorm" and "measured_I=" in rep["filters"][0] and "linear=true" in rep["filters"][0]
    after = music_enhance.measure(str(out))
    assert abs(after["integrated_lufs"] - -14.0) <= 0.5 and after["true_peak_dbfs"] <= -0.7 and after["sample_rate"] == 44100
    assert set(rep["before"]) == set(rep["after"]) >= {"integrated_lufs", "lra_lu", "true_peak_dbfs"}


