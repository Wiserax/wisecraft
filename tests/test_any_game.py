FFMPEG = pytest.mark.skipif(shutil.which("ffmpeg") is None or shutil.which("ffprobe") is None, reason="needs ffmpeg and ffprobe")
WAV = b"RIFF" + b"\0" * 2000


def make(root: Path, files: dict) -> Path:
    for rel, data in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data if isinstance(data, bytes) else data.encode())
    return root


def wise(*argv):
    try:
        cli.main([str(a) for a in argv])
    except SystemExit as e:
        if e.code:
            raise


def exit_code(*argv) -> int:
    with pytest.raises(SystemExit) as e:
        cli.main([str(a) for a in argv])
    return e.value.code or 0


def lavfi(out: Path, *args) -> Path:
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", *args, str(out)], check=True)
    return out


