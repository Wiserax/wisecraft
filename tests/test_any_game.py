# --------------------------------------------------------------------------- music-enhance

def tone(path: Path, seconds: float = 4, volume: float = 1.0) -> Path:
    """A stereo 1 kHz sine; lavfi's sine has a peak of 1/8, so volume 1 reads about -18 LUFS."""
    return lavfi(path, "-f", "lavfi", "-i", f"sine=frequency=1000:duration={seconds}:sample_rate=48000", "-af",
                 f"volume={volume},pan=stereo|c0=c0|c1=c0", "-c:a", "pcm_s16le")


@FFMPEG
@pytest.mark.parametrize("preset, target", [("music", -14.0), ("trailer", -14.0), ("voice", -16.0), ("game-sfx", -18.0)])
def test_enhance_a_tone_lands_on_the_preset(tmp_path, capsys, preset, target):
    src = tone(tmp_path / "tone.wav", volume=0.2)                                      # about -32 LUFS
    wise("music-enhance", src, "--for", preset, "--json")
    r = json.loads(capsys.readouterr().out)
    f = r["files"][0]
    out = tmp_path / "tone.enhanced.wav"
    assert r["ok"] and r["preset"] == preset and r["target"] == {"lufs": target, "true_peak_dbtp": -1.0} and Path(f["out"]) == out
    assert abs(f["before"]["integrated_lufs"] - -32.0) < 0.5
    after = music_enhance.measure(str(out))                                            # an independent reading of the file
    assert abs(after["integrated_lufs"] - target) <= 0.5 and after["true_peak_dbfs"] <= -1.0
    assert f["method"] == "gain" and abs(f["gain_db"] - (target + 32.0)) < 0.5         # peaks fit: one clean gain change
    assert (after["sample_rate"], after["channels"], after["codec"]) == (48000, 2, "pcm_s16le")
    assert src.stat().st_size > 0 and abs(music_enhance.measure(str(src))["integrated_lufs"] - -32.0) < 0.5   # the input is untouched


@FFMPEG
def test_enhance_uses_the_limiter_when_a_gain_would_clip(tmp_path, capsys):
    # pink noise that swells and fades: its peaks sit far above its average, so +22 dB of plain gain would clip
    src = lavfi(tmp_path / "dyn.wav", "-f", "lavfi", "-i", "anoisesrc=d=8:c=pink:r=44100:a=0.25:seed=7", "-af", "tremolo=f=0.5:d=0.9,volume=0.5", "-ac", "2")
    out = tmp_path / "out" / "dyn.flac"
    wise("music-enhance", src, "-o", out, "--report", tmp_path / "report.json")
    text = capsys.readouterr().out
    assert "loudnorm's second pass" in text and "result:        on target" in text and "before" in text and "after" in text
    rep = json.loads((tmp_path / "report.json").read_text())["files"][0]
    assert rep["method"] == "loudnorm" and "measured_I=" in rep["filters"][0] and "linear=true" in rep["filters"][0]
    after = music_enhance.measure(str(out))
    assert abs(after["integrated_lufs"] - -14.0) <= 0.5 and after["true_peak_dbfs"] <= -0.7 and after["sample_rate"] == 44100
    assert set(rep["before"]) == set(rep["after"]) >= {"integrated_lufs", "lra_lu", "true_peak_dbfs"}


@FFMPEG
def test_enhance_a_video_copies_the_picture(tmp_path, capsys):
    src = test_clip(tmp_path)
    wise("music-enhance", src, "--for", "trailer", "--eq", "--fade-in", "0.2", "--fade-out", "0.5", "--report", tmp_path / "r.md")
    text = capsys.readouterr().out
    out = tmp_path / "clip.enhanced.mp4"
    assert "picture:       copied as it is" in text and "highpass=f=30" in text and "afade=t=out:st=2.500:d=0.500" in text
    assert "```" in (tmp_path / "r.md").read_text() and "-14" in (tmp_path / "r.md").read_text()

    def packets(p):       # the video stream's packets, byte for byte
        return subprocess.run(["ffmpeg", "-v", "error", "-i", str(p), "-map", "0:v:0", "-c", "copy", "-f", "md5", "-"], capture_output=True, text=True).stdout
    assert packets(src) == packets(out) and packets(out).startswith("MD5=")
    r = clip.fingerprint(out)
    assert abs(r["audio"]["loudness"]["integrated_lufs"] - -14.0) <= 0.5 and r["video"]["frames"] == 90
    assert not any("music-enhance" in x["do"] for x in r["routes"])                   # nothing left to fix


@FFMPEG
def test_enhance_edges(tmp_path, capsys):
    a, b = tone(tmp_path / "a.wav", volume=0.5), tone(tmp_path / "blip.wav", seconds=0.1, volume=7.9)
    silent = lavfi(tmp_path / "silent.wav", "-f", "lavfi", "-i", "anullsrc=r=48000:cl=stereo", "-t", "1")
    wise("music-enhance", a, b, silent, "--out-dir", tmp_path / "fixed", "--json")
    files = {Path(f["file"]).name: f for f in json.loads(capsys.readouterr().out)["files"]}
    assert files["a.wav"]["ok"] and Path(files["a.wav"]["out"]) == tmp_path / "fixed" / "a.wav"
    # too short for a loudness reading: nothing is invented, the peak (about -0.1 dBFS) is pulled under the ceiling
    assert files["blip.wav"]["method"] == "peak" and files["blip.wav"]["after"]["integrated_lufs"] is None
    assert files["blip.wav"]["before"]["true_peak_dbfs"] > -1.0 >= files["blip.wav"]["after"]["true_peak_dbfs"] - 0.05
    assert files["silent.wav"]["method"] == "copy" and files["silent.wav"]["ok"]
    assert exit_code("music-enhance", a, "-o", a) == 1 and "overwrite the input" in capsys.readouterr().out
    assert exit_code("music-enhance", a, b, "-o", tmp_path / "x.wav") == 2
    assert exit_code("music-enhance", a, "-o", tmp_path / "x.xyz") == 1 and "don't know how to write" in capsys.readouterr().out
    assert exit_code("music-enhance", a, "--true-peak", "3") == 2 and exit_code("music-enhance", a, "--fade-in", "-1") == 2
    assert exit_code("music-enhance", tmp_path / "nope.wav") == 2
    wise("music-enhance", a, "--target", "-20", "--true-peak", "-3", "-o", tmp_path / "t.wav")
    assert abs(music_enhance.measure(str(tmp_path / "t.wav"))["integrated_lufs"] - -20.0) <= 0.5


def test_enhance_plan_and_commands_never_play():
    m = dict(integrated_lufs=-30.0, true_peak_dbfs=-20.0, lra_lu=5.0, silent=False,
             _norm={"input_i": "-30.00", "input_tp": "-20.00", "input_lra": "5.00", "input_thresh": "-40.5", "target_offset": "0.2"})
    easy = music_enhance.plan(m, -14.0, -1.0)
    assert easy["method"] == "gain" and easy["filters"] == ["volume=16.00dB"]
    hot = music_enhance.plan(dict(m, true_peak_dbfs=-6.0), -14.0, -1.0)
    assert hot["method"] == "loudnorm" and hot["filters"][0].startswith("loudnorm=I=-14.00:TP=-1.00:LRA=5.0:measured_I=-30.00")
    assert music_enhance.plan(dict(m, integrated_lufs=None, true_peak_dbfs=-0.2), -14.0, -1.0)["filters"] == ["volume=-0.80dB"]
    assert music_enhance.plan(dict(m, silent=True), -14.0, -1.0)["method"] == "copy"
    assert music_enhance.PRESETS == {"music": -14.0, "trailer": -14.0, "voice": -16.0, "game-sfx": -18.0} and music_enhance.CEILING == -1.0
    cmd = " ".join(music_enhance.command("ffmpeg", "x.wav", pre=["highpass=f=30"]))
    assert "[0:a:0]highpass=f=30,asplit=2" in cmd and "ffplay" not in cmd and "-f null" in cmd
    assert music_enhance.codec_args(Path("x.mp3"), {"bitrate_kbps": 96}, "ffmpeg") == ["-c:a", "libmp3lame", "-b:a", "128k"]
    assert music_enhance.codec_args(Path("x.wav"), {"codec": "pcm_s24le"}, "ffmpeg") == ["-c:a", "pcm_s24le"]
