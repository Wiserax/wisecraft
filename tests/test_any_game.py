def test_enhance_plan_and_commands_never_play():
    m = dict(integrated_lufs=-30.0, true_peak_dbfs=-20.0, lra_lu=5.0, silent=False,
             _norm={"input_i": "-30.00", "input_tp": "-20.00", "input_lra": "5.00", "input_thresh": "-40.5", "target_offset": "0.2"})
    easy = music_enhance.plan(m, -14.0, -1.0)
    assert easy["method"] == "gain" and easy["filters"] == ["volume=16.00dB"]
    hot = music_enhance.plan(dict(m, true_peak_dbfs=-6.0), -14.0, -1.0)
