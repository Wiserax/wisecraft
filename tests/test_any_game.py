def test_clip(tmp_path: Path, name: str = "clip.mp4", audio: bool = True) -> Path:
    """3 s, 320x180 at 30 fps: 1 s of black, then a test pattern, then a flat red card (two cuts); a quiet 440 Hz tone."""
    args = ["-f", "lavfi", "-i", "color=c=black:s=320x180:r=30:d=1", "-f", "lavfi", "-i", "testsrc2=s=320x180:r=30:d=1",
            "-f", "lavfi", "-i", "color=c=red:s=320x180:r=30:d=1"]
    graph = "[0:v][1:v][2:v]concat=n=3:v=1[v]"
    maps = ["-map", "[v]"]
    if audio:
        args += ["-f", "lavfi", "-i", "sine=f=440:d=3:r=48000"]
        graph += ";[3:a]volume=0.4[a]"
        maps += ["-map", "[a]", "-c:a", "aac"]
    return lavfi(tmp_path / name, *args, "-filter_complex", graph, *maps, "-c:v", "libx264", "-pix_fmt", "yuv420p")


